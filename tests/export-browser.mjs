import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
  await page.goto('http://127.0.0.1:5178');
  await page.locator('#package-input').setInputFiles('artifacts/project.retouch');
  await page.waitForFunction(()=>document.querySelector('.project-name').textContent.endsWith('· 导入'));
  await page.waitForFunction(()=>document.getElementById('saved').textContent!=='保存中…');
  await page.evaluate(async()=>{
    const db=await new Promise((resolve,reject)=>{const req=indexedDB.open('retouch-review',1);req.onsuccess=()=>resolve(req.result);req.onerror=()=>reject(req.error);});
    const tx=db.transaction('projects','readwrite'),store=tx.objectStore('projects');
    const all=store.getAll();all.onsuccess=()=>{
      const p=all.result[0],base=p.pairs[0];
      const empty=structuredClone(base);empty.id='empty';empty.versions[0].annotations=[];
      const passed=structuredClone(base);passed.id='passed';passed.versions[0].annotations.forEach(a=>a.status='已通过');
      p.pairs.push(empty,passed,{id:'unpaired',originalId:base.originalId,versionId:'',versions:[]});
      p.selectedPairId='unpaired';p.updatedAt=new Date().toISOString();store.put(p,p.id);
    };
    await new Promise((resolve,reject)=>{tx.oncomplete=resolve;tx.onerror=()=>reject(tx.error);});db.close();
  });
  await page.reload();
  await page.click('[data-action="annotated-photos"]');
  assert.equal(await page.locator('#pairs .photo-card').count(),2);
  assert.equal(await page.locator('#pairs .selected').getAttribute('data-pair')==='unpaired',false);
  assert.equal(await page.locator('.sidebar').isVisible(),true);
  assert.equal(await page.locator('[data-action="photo-prev"]').isEnabled(),false);
  await page.click('[data-action="photo-next"]');
  assert.equal(await page.locator('#pairs .selected').getAttribute('data-pair'),'passed');
  assert.equal(await page.locator('[data-action="photo-next"]').isEnabled(),false);
  await page.click('[data-action="photo-prev"]');
  assert.notEqual(await page.locator('#pairs .selected').getAttribute('data-pair'),'passed');
  await page.click('[data-action="annotated-photos"]');
  assert.equal(await page.locator('#pairs .photo-card').count(),4);
  await page.locator('[data-pair="unpaired"]').click();
  await page.click('[data-action="toggle-sidebar"]');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.click('[data-action="annotated-photos"]');
  await page.screenshot({path:'artifacts/annotated-photos-mobile.png'});
  await page.click('[data-action="annotated-photos"]');
  await page.locator('[data-pair="unpaired"]').click();
  await page.setViewportSize({width:1440,height:1000});
  await page.click('[data-action="export"]');
  await page.click('[data-export="pdf"]');
  await page.waitForFunction(()=>document.getElementById('export-status').textContent.includes('配对修图'));
  assert.ok(await page.locator('#export-status').isVisible());
  await page.selectOption('#export-scope','annotated');
  assert.match(await page.locator('#export-estimate').textContent(),/2 组/);
  await page.selectOption('#export-filter','pending');
  assert.match(await page.locator('#export-estimate').textContent(),/1 组/);
  const pngPromise=page.waitForEvent('download');await page.click('[data-export="png"]');
  const png=await pngPromise;assert.ok(png.suggestedFilename().endsWith('.png'));await png.saveAs('artifacts/filtered.png');
  await page.selectOption('#export-filter','all');
  const zipPromise=page.waitForEvent('download');await page.click('[data-export="png"]');
  const zip=await zipPromise;assert.ok(zip.suggestedFilename().endsWith('.zip'));await zip.saveAs('artifacts/filtered.zip');
  // Cancel at a real asynchronous page boundary, before any download is issued.
  let downloads=0;page.on('download',()=>downloads++);
  await page.evaluate(()=>{
    const status=document.getElementById('export-status');
    const observer=new MutationObserver(()=>{if(status.textContent.includes('PDF 第')){document.getElementById('cancel-export').click();observer.disconnect();}});
    observer.observe(status,{childList:true,subtree:true,characterData:true});
  });
  await page.click('[data-export="pdf"]');
  await page.waitForFunction(()=>document.getElementById('export-status').textContent.includes('导出已取消'));
  assert.equal(downloads,0);assert.equal(await page.locator('[data-export="pdf"]').isEnabled(),true);
  const pdfPromise=page.waitForEvent('download');await page.click('[data-export="pdf"]');
  const pdf=await pdfPromise;await pdf.saveAs('artifacts/filtered.pdf');
  const pdfBytes=await fs.readFile('artifacts/filtered.pdf');
  assert.equal((pdfBytes.toString('latin1').match(/\/Type \/Page\b/g)||[]).length,2,'two annotated photos should have two detail pages, without duplicate overviews');
  await page.selectOption('#export-scope','selected');
  for(const checkbox of await page.locator('#export-pairs input:checked').all())await checkbox.uncheck();
  await page.click('[data-export="png"]');assert.match(await page.locator('#export-status').textContent(),/没有符合条件/);
  await page.locator('#export-pairs input[value="empty"]').check();
  const emptyPdfPromise=page.waitForEvent('download');await page.click('[data-export="pdf"]');
  const emptyPdf=await emptyPdfPromise;await emptyPdf.saveAs('artifacts/no-annotations.pdf');
  assert.equal(((await fs.readFile('artifacts/no-annotations.pdf')).toString('latin1').match(/\/Type \/Page\b/g)||[]).length,1,'unannotated selected photo retains one overview');
  console.log('PASS: visible export errors, annotated/current-version/status filtering, single PNG, multi PNG ZIP, PDF cancellation without download, retry, empty selection.');
}finally{await browser.close();}
